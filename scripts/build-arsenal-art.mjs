// Arsenal icons (SYS-15): until the kit draws an arsenal weapon, it wears its look's tile (src/ui/art) with a short
// name in the corner, so weapons that share a look still tell apart. A drawn weapon (K9; art/ui-art-spec.mjs
// ARSENAL_ART) has its own cells in uiArt.generated.css and gets neither. Writes src/ui/art/arsenalArt.generated.css
// from the arsenal table and the positions in uiArt.generated.css. Deterministic; run after build:ui-art.
// Usage: node scripts/build-arsenal-art.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import ARSENAL from '../src/content/data/arsenal.ts';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const artDir = path.join(root, 'src/ui/art');
const strings = JSON.parse(readFileSync(path.join(root, 'public/assets/content/strings/ko.json'), 'utf8'));
const generated = readFileSync(path.join(artDir, 'uiArt.generated.css'), 'utf8');
const positions = new Map();
for (const [, cls, key, position] of generated.matchAll(/\.(art[A-Za-z]+)\[data-art="([^"]+)"\] \{ background-position: ([^;]+); \}/g)) positions.set(`${cls}|${key}`, position);
/** Weapons with their own tile and slot cells (the keyed arsenal sheets of build:ui-art). */
const drawn = new Set([...generated.matchAll(/\.artTile\[data-art="([^"]+)"\] \{ background-image:/g)].map((match) => match[1]));
for (const key of drawn) {
  if (!key.endsWith('-awakened') && !drawn.has(`${key}-awakened`)) throw new Error(`${key} has no awakened tile`);
  if (!generated.includes(`.artSlot[data-art="${key}"] { background-image:`)) throw new Error(`${key} has a tile but no slot`);
}

/** Two syllables: the whole name if that short, else its first and last. */
function shortName(name) {
  const letters = [...name.replace(/\s/g, '')];
  return letters.length <= 2 ? letters.join('') : letters[0] + letters.at(-1);
}

// The badges match data-art by prefix (the awakened cell adds -awakened), so no skill id may begin with another's.
const allIds = [...Object.keys(JSON.parse(readFileSync(path.join(root, 'public/assets/content/strings/ko.json'), 'utf8'))).filter((key) => /^skill\.[A-Za-z]+$/.test(key)).map((key) => key.slice(6))];
for (const id of Object.keys(ARSENAL.weapons)) {
  const clash = allIds.find((other) => other !== id && other.startsWith(id));
  if (clash) throw new Error(`${clash} begins with ${id}`);
}
const rules = [];
const badges = [];
const seen = new Map();
const badged = Object.entries(ARSENAL.weapons).filter(([id]) => !drawn.has(id));
for (const [id, weapon] of badged) {
  const badge = shortName(strings[`skill.${id}`]);
  if (seen.has(badge)) throw new Error(`${id} and ${seen.get(badge)} share the badge ${badge}`);
  seen.set(badge, id);
  for (const cls of ['artTile', 'artSlot']) {
    for (const suffix of ['', '-awakened']) {
      const position = positions.get(`${cls}|${weapon.look}${suffix}`);
      if (!position) throw new Error(`no ${cls} cell for ${weapon.look}${suffix}`);
      rules.push(`.${cls}[data-art="${id}${suffix}"] { background-position: ${position}; }`);
    }
    badges.push(`.${cls}[data-art^="${id}"]::after { content: "${badge}"; }`);
  }
}
const selectors = badged.flatMap(([id]) => [`.artTile[data-art^="${id}"]`, `.artSlot[data-art^="${id}"]`]);
const header = `/* Generated by scripts/build-arsenal-art.mjs from src/content/data/arsenal.ts. Do not edit.
   SYS-15: an arsenal weapon wears its look's tile until the kit draws its own, with a two-syllable badge.
   Drawn by the kit (uiArt.generated.css): ${[...drawn].filter((key) => !key.endsWith('-awakened')).join(', ') || 'none'}. */`;
// With every weapon drawn there is nothing to badge, and a rule with no selector is a syntax error (TEC-05: two
// esbuild warnings on every build), so the badge rules are left out.
const badgeRules = selectors.length === 0 ? '' : `
${selectors.join(',\n')} {
  position: relative;
}
${selectors.map((selector) => `${selector}::after`).join(',\n')} {
  position: absolute;
  right: 0;
  bottom: 0;
  padding: 0 2px;
  border-radius: 3px;
  background: #101312;
  color: #fffff8;
  font: 700 13px/1.1 system-ui, sans-serif;
}
`;
const css = `${header}\n${badgeRules}${[...rules, ...badges].map((line) => `${line}\n`).join('')}`;
writeFileSync(path.join(artDir, 'arsenalArt.generated.css'), css);
console.log(`${Object.keys(ARSENAL.weapons).length} weapons, ${drawn.size / 2} drawn, ${rules.length} tile rules for the rest`);
