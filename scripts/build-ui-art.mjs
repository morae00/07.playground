// UI art baker (ART-09): renders the concept-kit drawings listed in art/ui-art-spec.mjs in Chromium, lays each sheet
// out as a grid of equal cells at @2x, and writes WebP sheets plus a generated stylesheet into src/ui/art. It also
// composes the story panels (CON-06) into one WebP each in public/assets/packs/story.
// Usage: node scripts/build-ui-art.mjs [sheets|story]   (both by default; deterministic for the same kit, spec, and
// Chromium)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { COLOR_MAP } from '../art/atlas-spec.mjs';
import { STORY_PANEL, STORY_PANELS, UI_ART_DENSITY, UI_ART_QUALITY, UI_SHEETS } from '../art/ui-art-spec.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const kitDir = path.join(root, 'art/concept-kit');
const outDir = path.join(root, 'src/ui/art');
const storyDir = path.join(root, 'public/assets/packs/story');
const only = process.argv[2];
const KIT_FILES = ['lib.js', 'k-hero.js', 'k-bosses1.js', 'k-bosses2.js', 'k-bosses3.js', 'k-bosses4.js', 'k-icons.js', 'k-icons2.js', 'k-enemies.js', 'k-env.js'];

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.setContent('<!doctype html><html><body></body></html>');
  for (const file of KIT_FILES) await page.addScriptTag({ content: readFileSync(path.join(kitDir, file), 'utf8') });

  if (only !== 'story') await bakeSheets(page);
  if (only !== 'sheets') {
    mkdirSync(storyDir, { recursive: true });
    for (const [key, scene] of Object.entries(STORY_PANELS)) {
      const result = await page.evaluate(renderPanel, { key, scene, panel: STORY_PANEL, quality: UI_ART_QUALITY, colorMap: COLOR_MAP });
      writeFileSync(path.join(storyDir, `${key}.webp`), Buffer.from(result.webp.split(',')[1], 'base64'));
      console.log(`story/${key}: ${result.width}x${result.height}, ${Math.round(result.bytes / 1024)} KiB`);
    }
  }
} finally {
  await browser.close();
}

async function bakeSheets(page) {
  mkdirSync(outDir, { recursive: true });
  let css = `/* Generated by scripts/build-ui-art.mjs from art/ui-art-spec.mjs and art/concept-kit. Do not edit.
   Provenance: concept-kit drawings (AI-assisted concept art, provisional until hand-cleaned art replaces them).
   Each class shows one cell of its sheet, chosen by data-art, scaled to the element: give the element a width
   (the aspect ratio is set here). The drawing sits inside the cell as art/ui-art-spec.mjs describes. */
`;
  for (const [name, sheet] of Object.entries(UI_SHEETS)) {
    const result = await page.evaluate(renderSheet, { sheet, density: UI_ART_DENSITY, quality: UI_ART_QUALITY, colorMap: COLOR_MAP });
    writeFileSync(path.join(outDir, `${sheet.file}.webp`), Buffer.from(result.webp.split(',')[1], 'base64'));
    const rows = Math.ceil(sheet.items.length / sheet.columns);
    const [cellWidth, cellHeight] = sheet.cell;
    // A keyed sheet shares another sheet's class and cell: each of its keys names the image and its size itself.
    if (sheet.keyed) {
      const base = Object.values(UI_SHEETS).find((other) => !other.keyed && other.className === sheet.className);
      if (!base || base.cell.join() !== sheet.cell.join()) throw new Error(`${name}: a keyed sheet needs a ${sheet.className} sheet with its cell`);
      css += '\n';
    } else {
      css += `\n.${sheet.className} {\n  aspect-ratio: ${cellWidth} / ${cellHeight};\n  background-image: url("./${sheet.file}.webp");\n  background-repeat: no-repeat;\n  background-size: ${sheet.columns * 100}% ${rows * 100}%;\n}\n`;
    }
    sheet.items.forEach((item, index) => {
      const column = index % sheet.columns;
      const row = Math.floor(index / sheet.columns);
      const position = `background-position: ${percent(column, sheet.columns)} ${percent(row, rows)};`;
      css += sheet.keyed
        ? `.${sheet.className}[data-art="${item.key}"] { background-image: url("./${sheet.file}.webp"); background-size: ${sheet.columns * 100}% ${rows * 100}%; ${position} }\n`
        : `.${sheet.className}[data-art="${item.key}"] { ${position} }\n`;
    });
    console.log(`${name}: ${sheet.items.length} cells, ${result.width}x${result.height}, ${Math.round(result.bytes / 1024)} KiB`);
  }
  writeFileSync(path.join(outDir, 'uiArt.generated.css'), css);
}

/** Background position that puts cell `index` of `count` in view when the image is `count` elements wide. */
function percent(index, count) {
  return count > 1 ? `${Number(((index / (count - 1)) * 100).toFixed(4))}%` : '0%';
}

// ---- browser side ----

async function renderSheet({ sheet, density, quality, colorMap }) {
  const PN = window.PN;
  const K = PN.icons.K;
  const f = (value) => Math.round(value * 100) / 100;

  /** The bonus card glyphs, centred on the origin, sized for the 120 window of a 150 card. */
  const bonusGlyph = {
    heal: () => `<g transform="translate(-52 -56)">${PN.icons.pickup('heal', { size: 104 })}</g>`,
    coins: () => [[-24, 10], [24, 10], [0, -22]].map(([x, y]) => `<g transform="translate(${x - 34} ${y - 36})">${PN.icons.pickup('coin', { size: 68 })}</g>`).join(''),
    overdrive: () => `<g transform="scale(3.1)">${PN.vfx.hit(1, { angle: -35, crit: true, seed: 3 })}</g>`,
  };

  /**
   * Keeps the first of an attribute a tag repeats. The kit's Ch4 enemies repeat stroke-linejoin, which browsers
   * render in the DOM but refuse in an SVG image (the atlas bake does the same, build-atlas.mjs).
   */
  const firstAttributes = (markup) => markup.replace(/<([a-zA-Z][\w:-]*)((?:\s+[\w:-]+="[^"]*")+)(\s*\/?)>/g, (tag, name, attributes, end) => {
    const seen = new Set();
    let repeated = false;
    const kept = attributes.replace(/\s+([\w:-]+)="[^"]*"/g, (attribute, key) => {
      if (!seen.has(key)) {
        seen.add(key);
        return attribute;
      }
      repeated = true;
      return '';
    });
    return repeated ? `<${name}${kept}${end}>` : tag;
  });

  /** The drawn bounds of some markup, in its own units (defs excluded). */
  const bounds = (markup) => {
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.innerHTML = markup;
    document.body.appendChild(svg);
    const box = svg.getBBox();
    svg.remove();
    return box;
  };

  const recipes = {
    tile: (id, awakened) => PN.icons.tile(id, { awakened, metal: true, size: 150 }),
    // The frame's window centre is (80, 80) of 160, which is 75 at 150.
    bonusTile: (bonus, rarity) => `${PN.icons.frame(rarity, { metal: true, size: 150 })}<g transform="translate(75 74)">${bonusGlyph[bonus]()}</g>`,
    // SYS-15 (K9): the arsenal's own tiles and slots, framed like the core skills'.
    arsenalTile: (id, awakened) => PN.arsenal.tile(id, { awakened, metal: true, size: 150 }),
    arsenalSlot: (id, awakened) => PN.arsenal.hudSlot(id, { size: 40, awakened }).replace(/<rect x="46\.4"[^>]*\/>/g, ''),
    slot: (id, awakened) => {
      // hudSlot draws the plain icon; an awakened skill shows its awakened icon in the same slot.
      const skill = PN.icons.skill;
      if (awakened) PN.icons.skill = (skillId, options) => skill(skillId, { ...options, awakened: true });
      try {
        return PN.icons.hudSlot(id, { size: 40 }).replace(/<rect x="46\.4"[^>]*\/>/g, '');
      } finally {
        PN.icons.skill = skill;
      }
    },
    heroPortrait: (expr) => `<g transform="scale(0.6)">${PN.heroKit.portrait(expr)}</g>`,
    // Framed like PN.heroKit.portrait: a 74 disc with a paper halftone vignette, a 6 ink ring and a paper ring.
    // Enraged bosses get the coral dashed ring (the kit shows coral on bosses only when they are enraged).
    bossPortrait: ({ kit, module = 'bossesA', center, scale, detail = 'game' }, enraged) => {
      // bossesA draws in a 400 box; bossesB and fieldBosses in a 384 box with their own detail option. Field bosses
      // have no enraged drawing (API-bosses4): their enraged portrait is the calm one in the coral ring.
      const k = 148 / (scale * (module === 'bossesA' ? 400 : 384));
      const body = module === 'bossesA'
        ? PN.bossesA.draw(kit, { phase: 1, enraged, lod: 'game', halo: false, shadow: false, fx: true })
        : PN[module].draw(kit, { phase: 1, enraged, detail, halo: false, shadow: false });
      const vignette = PN.halftone(0, 0, 160, 160, 5, (x, y) => Math.max(0, Math.min(1.9, (Math.hypot(x - 80, y - 70) - 44) / 30)), K.ink1, 45);
      const ring = `<circle cx="80" cy="80" r="74" fill="none" stroke="${K.ink}" stroke-width="6"/><circle cx="80" cy="80" r="78.5" fill="none" stroke="${K.p50}" stroke-width="2.4"/>`;
      const rage = enraged ? `<circle cx="80" cy="80" r="74" fill="none" stroke="${K.hostile}" stroke-width="2.4" stroke-dasharray="14 6"/>` : '';
      return `<g transform="scale(0.6)"><defs><clipPath id="disc"><circle cx="80" cy="80" r="74"/></clipPath></defs><g clip-path="url(#disc)"><rect width="160" height="160" fill="${K.paper}"/>${vignette}<g transform="translate(${f(80 - center[0] * k)} ${f(80 - center[1] * k)}) scale(${f(k)})">${body}</g></g>${ring}${rage}</g>`;
    },
    pickup: (kind) => PN.icons.pickup(kind, { tier: 1, size: 24 }),
    keyart: (pose) => `<g transform="scale(0.9)">${PN.heroKit.full(pose, { scaleHint: 0.9, ground: false })}</g>`,
    landmark: (ch) => `<g transform="scale(0.6)">${PN.env.landmark(ch)}</g>`,
    // Enemies draw in role boxes whose horns and tails reach past the box, so they are fitted by their drawn bounds.
    // Shock's burst spikes reach past its circle, so it draws smaller.
    hazard: (kind) => PN.env.hazard(kind, 'static', { r: kind === 'shock' ? 16 : 22 }),
    enemyIcon: (ch, role) => {
      const markup = PN.enemies.draw(ch, role, { lod: 'game', halo: false, shadow: false });
      const box = bounds(markup);
      const [width, height] = sheet.cell;
      const scale = Math.min((width - 6) / box.width, (height - 6) / box.height);
      return `<g transform="translate(${f(width / 2 - (box.x + box.width / 2) * scale)} ${f(height / 2 - (box.y + box.height / 2) * scale)}) scale(${f(scale)})">${markup}</g>`;
    },
  };

  const [cellWidth, cellHeight] = sheet.cell;
  const [originX, originY] = sheet.origin;
  const w = Math.round(cellWidth * density);
  const h = Math.round(cellHeight * density);
  const rows = Math.ceil(sheet.items.length / sheet.columns);
  const canvas = document.createElement('canvas');
  canvas.width = w * sheet.columns;
  canvas.height = h * rows;
  const ctx = canvas.getContext('2d');
  const probe = document.createElement('canvas');
  probe.width = w;
  probe.height = h;
  const probeCtx = probe.getContext('2d', { willReadFrequently: true });

  for (let index = 0; index < sheet.items.length; index += 1) {
    const item = sheet.items[index];
    let markup = recipes[item.recipe](...item.args);
    if (!markup) throw new Error(`${sheet.file}/${item.key} has no drawing`);
    markup = firstAttributes(markup);
    for (const [from, to] of colorMap) markup = markup.replace(new RegExp(from, 'gi'), to);
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="${originX} ${originY} ${cellWidth} ${cellHeight}">${markup}</svg>`;
    const image = new Image();
    image.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
    await image.decode().catch((error) => {
      throw new Error(`${sheet.file}/${item.key} did not decode as SVG (${error.message})`);
    });
    probeCtx.clearRect(0, 0, w, h);
    probeCtx.drawImage(image, 0, 0);
    // A drawing that reaches the cell edge would be cut off, and at small sizes it would bleed into its neighbours.
    const { data } = probeCtx.getImageData(0, 0, w, h);
    let painted = false;
    for (let y = 0; y < h; y += 1) {
      for (let x = 0; x < w; x += 1) {
        if (data[(y * w + x) * 4 + 3] === 0) continue;
        painted = true;
        if (!sheet.bleed && (x === 0 || y === 0 || x === w - 1 || y === h - 1)) throw new Error(`${sheet.file}/${item.key} touches the cell edge at ${x},${y}`);
      }
    }
    if (!painted) throw new Error(`${sheet.file}/${item.key} rendered empty`);
    ctx.drawImage(probe, (index % sheet.columns) * w, Math.floor(index / sheet.columns) * h);
  }
  const webp = canvas.toDataURL('image/webp', quality);
  return { webp, width: canvas.width, height: canvas.height, bytes: Math.round(((webp.length - webp.indexOf(',') - 1) * 3) / 4) };
}

/** One story panel (CON-06): the scene art/ui-art-spec.mjs describes, drawn at the panel's size and density. */
async function renderPanel({ key, scene, panel, quality, colorMap }) {
  const PN = window.PN;
  const K = PN.icons.K;
  const f = (value) => Math.round(value * 100) / 100;
  const [W, H] = panel.size;
  const ground = panel.ground;
  const parts = [scene.ch && !scene.paper ? PN.env.landmark(scene.ch, { w: W, h: H }) : `<rect width="${W}" height="${H}" fill="${K.paper}"/>`];
  if (scene.blank) {
    // The void: plain paper over the scene from `from` rightwards, its edge torn by turbulence and fringed in ink.
    const x = scene.blank.from;
    parts.push(`<defs><filter id="story-rag" x="-20%" y="-20%" width="140%" height="140%"><feTurbulence type="fractalNoise" baseFrequency="0.045" numOctaves="2" seed="7"/><feDisplacementMap in="SourceGraphic" scale="30" xChannelSelector="R" yChannelSelector="G"/></filter></defs>`
      + `<g filter="url(#story-rag)"><rect x="${x}" y="-40" width="${W - x + 80}" height="${H + 80}" fill="${K.p50}" stroke="${K.ink1}" stroke-width="2.6"/></g>`);
  }
  if (scene.margin !== undefined) {
    const x = scene.margin;
    parts.push(`<rect x="${x}" y="0" width="${W - x}" height="${H}" fill="${K.p50}"/><path d="M${x} 0 V${H} M${x + 7} 0 V${H}" stroke="${K.ink}" stroke-width="2.2"/>`);
  }
  if (scene.seam !== undefined) {
    const x = scene.seam;
    let stitches = '';
    for (let y = 12; y < H; y += 26) stitches += `M${x - 9} ${y - 7} L${x + 9} ${y + 7} `;
    parts.push(`<path d="M${x} 0 V${H}" stroke="${K.ink}" stroke-width="3" stroke-dasharray="11 7"/><path d="${stitches}" stroke="${K.ink}" stroke-width="2.4" stroke-linecap="round"/>`);
  }
  // Bodies stand on the ground line by their feet, the farthest first.
  const place = (markup, [footX, footY], x, scale, flip = false, extra = '') => `<g transform="translate(${f(flip ? x + footX * scale : x - footX * scale)} ${f(ground - footY * scale)}) scale(${f(flip ? -scale : scale)} ${f(scale)})"${extra}>${markup}</g>`;
  if (scene.boss) {
    const { kit, module = 'bossesA', x, scale, fallen } = scene.boss;
    // A fallen ruler is its kit fall's second frame (K3-2), faint: its line going out of the manuscript.
    const pose = fallen ? { pose: 'death', frame: 1 } : { phase: 3 };
    const body = module === 'bossesB'
      ? PN.bossesB.draw(kit, { ...pose, detail: 'art', halo: false, shadow: !fallen })
      : PN.bossesA.draw(kit, { ...pose, lod: 'art', halo: false, shadow: !fallen, fx: false });
    const feet = module === 'bossesB' ? [192, 360] : [200, 392];
    parts.push(place(body, feet, x, scale, false, fallen ? ` opacity="0.42"` : ''));
  }
  for (const [role, x, scale, flip] of scene.enemies ?? []) {
    parts.push(place(PN.enemies.draw(scene.ch, role, { lod: 'art', halo: false }), PN.enemies.meta(scene.ch, role).feet, x, scale, flip));
  }
  if (scene.hero) {
    const { pose, x, scale, flip } = scene.hero;
    parts.push(place(PN.heroKit.full(pose, { scaleHint: scale * panel.density, ground: true }), [200, 600], x, scale, flip));
  }
  if (scene.drop) {
    const [x, y] = scene.drop;
    parts.push(`<circle cx="${x}" cy="${y}" r="7.5" fill="${K.ink}"/><circle cx="${x + 11}" cy="${y - 6}" r="2.2" fill="${K.ink}"/><circle cx="${x - 9}" cy="${y + 8}" r="1.6" fill="${K.ink}"/><path d="M${x} ${y + 7} q 2 9 -1 15" stroke="${K.ink}" stroke-width="2.4" fill="none" stroke-linecap="round"/>`);
  }
  let markup = parts.join('');
  // Keeps the first of an attribute a tag repeats, as the sheet bake does (the kit's Ch4 enemies repeat one).
  markup = markup.replace(/<([a-zA-Z][\w:-]*)((?:\s+[\w:-]+="[^"]*")+)(\s*\/?)>/g, (tag, name, attributes, end) => {
    const seen = new Set();
    let repeated = false;
    const kept = attributes.replace(/\s+([\w:-]+)="[^"]*"/g, (attribute, attr) => {
      if (!seen.has(attr)) {
        seen.add(attr);
        return attribute;
      }
      repeated = true;
      return '';
    });
    return repeated ? `<${name}${kept}${end}>` : tag;
  });
  for (const [from, to] of colorMap) markup = markup.replace(new RegExp(from, 'gi'), to);
  const w = Math.round(W * panel.density);
  const h = Math.round(H * panel.density);
  const image = new Image();
  image.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${W} ${H}">${markup}</svg>`)}`;
  await image.decode().catch((error) => {
    throw new Error(`story/${key} did not decode as SVG (${error.message})`);
  });
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = K.paper;
  ctx.fillRect(0, 0, w, h);
  ctx.drawImage(image, 0, 0);
  const webp = canvas.toDataURL('image/webp', quality);
  return { webp, width: w, height: h, bytes: Math.round(((webp.length - webp.indexOf(',') - 1) * 3) / 4) };
}
